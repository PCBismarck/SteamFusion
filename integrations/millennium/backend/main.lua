---@ffi
---@return boolean
function fusion_settings() return spawn("settings") end

---@ffi
---@param steamId string
---@param payload string
---@return boolean
function fusion_catalog(steamId, payload)
    if environment ~= "native" or not steamId:match("^765%d%d%d%d%d%d%d%d%d%d%d%d%d%d$") or #payload > 4194304 then return false end
    local path = state .. "\\catalogs\\" .. steamId .. ".json"
    local f = io.open(path .. ".tmp", "wb")
    if not f then return false end
    f:write(payload); f:close()
    os.remove(path)
    return os.rename(path .. ".tmp", path) ~= nil
end

---@ffi
---@param steamId string
---@param loggedOn boolean
---@return boolean
function fusion_signal(steamId, loggedOn)
    if steamId ~= "" and not steamId:match("^765%d%d%d%d%d%d%d%d%d%d%d%d%d%d$") then return false end
    local pid = steam_pid()
    if pid == 0 then return false end
    local path = state .. "\\signals\\" .. environment .. ".json"
    local f = io.open(path .. ".tmp", "wb")
    if not f then return false end
    f:write(string.format('{"pid":%d,"steamId":"%s","loggedOn":%s,"runningGames":[],"activityKnown":false,"timestamp":%d,"environment":"%s"}',
        pid, steamId, loggedOn and "true" or "false", os.time() * 1000, environment))
    f:close()
    -- Windows rename cannot replace an existing file; a missing sample is treated as Unknown.
    os.remove(path); return os.rename(path .. ".tmp", path) ~= nil
end

local function on_load()
    if ffi.os ~= "Windows" then error("SteamFusion 当前只支持 Windows") end
    local ok, sbie = pcall(ffi.load, "SbieDll")
    if ok then
        local box = ffi.new("WCHAR[34]"); local image = ffi.new("WCHAR[96]"); local sid = ffi.new("WCHAR[96]"); local session = ffi.new("DWORD[1]")
        if sbie.SbieApi_QueryProcess(ffi.cast("HANDLE", kernel.GetCurrentProcessId()), box, image, sid, session) == 0 and box[0] ~= 0 then
            local chars = {}; for i = 0, 32 do if box[i] == 0 then break end; chars[#chars + 1] = string.char(box[i]) end
            local name = table.concat(chars)
            if not name:match("^[A-Za-z][A-Za-z0-9_]*$") then error("不支持的沙盒名") end
            environment = name
        end
    end
    millennium.ready()
    logger:info("SteamFusion environment: " .. environment)
end
return { on_load = on_load, on_unload = function() end }
